-- Magic Cake: generate an EarthBound battle-background video whose background
-- switches at each lyric section. Sections are runs of time-consecutive lines
-- that share a Style (e.g. Intro / Verse / Chorus). Requires magic-cake
-- (https://github.com/cassdeckard/MagicCake) plus node and ffmpeg.
script_name = "Magic Cake: Generate section backgrounds"
script_description = "Render a battle-background video that changes background at each Style section"
script_author = "Cass D"
script_version = "1.1"

local M = {}
local TAG = "magic-cake"   -- Effect of the Comment lines that store saved choices

-- Lines that count as lyrics: real Dialogue (not templater output/templates/code),
-- plus karaoke source lines that the templater turned into Comments.
function M.is_lyric(l)
  if l.class ~= "dialogue" then return false end
  local fx = (l.effect or ""):lower()
  if l.comment then return fx == "karaoke" end
  if fx == "fx" or fx:match("^template") or fx:match("^code") or fx == TAG then return false end
  return true
end

-- Section group for a style: "-furigana" maps to its base style, and every
-- "Title" / "Title-*" style (and "Credits" / "Credits-*") shares one group.
function M.group(style)
  local g = (style or ""):gsub("%-furigana$", "")
  if g == "Title" or g:match("^Title%-") then return "Title" end
  if g == "Credits" or g:match("^Credits%-") then return "Credits" end
  return g
end

-- Saved pick for a group, falling back to an old per-style key (e.g. bg:Title-Song).
function M.saved_bg(bg, grp)
  if bg[grp] then return bg[grp] end
  local keys = {}
  for k in pairs(bg) do if M.group(k) == grp then keys[#keys + 1] = k end end
  table.sort(keys)
  return keys[1] and bg[keys[1]] or nil
end

-- Returns sections {style=<group>, start=ms, finish=ms} and the last lyric end (ms).
function M.sections(lines, end_ms)
  local ly, seen = {}, {}
  for _, l in ipairs(lines) do
    if M.is_lyric(l) then
      local k = l.start_time .. "|" .. l.end_time .. "|" .. l.style .. "|" .. (l.text or ""):gsub("{[^}]*}", "")
      if not seen[k] then seen[k] = true; ly[#ly + 1] = l end
    end
  end
  table.sort(ly, function(a, b)
    if a.start_time ~= b.start_time then return a.start_time < b.start_time end
    return a.end_time < b.end_time end)
  local secs, last_end = {}, 0
  for _, l in ipairs(ly) do
    if l.end_time > last_end then last_end = l.end_time end
    local cur = secs[#secs]
    local g = M.group(l.style)
    if not cur or cur.style ~= g then
      if cur then cur.finish = l.start_time end
      secs[#secs + 1] = { style = g, start = (#secs == 0) and 0 or l.start_time }
    end
  end
  if #secs > 0 then secs[#secs].finish = end_ms or (last_end + 3000) end
  return secs, last_end
end

function M.distinct_styles(secs)
  local out, seen = {}, {}
  for _, s in ipairs(secs) do if not seen[s.style] then seen[s.style] = true; out[#out + 1] = s.style end end
  return out
end

function M.chain_text(secs, specs)
  local t = { "# start(seconds) spec   -- generated by magic-cake.lua" }
  for _, s in ipairs(secs) do
    t[#t + 1] = string.format("%.3f %s   # %s", s.start / 1000, specs[s.style], s.style)
  end
  return table.concat(t, "\n") .. "\n"
end

function M.shq(s) return "'" .. tostring(s):gsub("'", "'\\''") .. "'" end

-- Saved choices: Comment lines with Effect "magic-cake", Text "bg:<Style>=<spec>" or "opt:<key>=<value>"
function M.load_saved(subs)
  local bg, opt, idx = {}, {}, {}
  for i = 1, #subs do
    local l = subs[i]
    if l.class == "dialogue" and l.comment and l.effect == TAG then
      local kind, k, v = l.text:match("^(%a+):([^=]*)=(.*)$")
      if kind == "bg" then bg[k] = v elseif kind == "opt" then opt[k] = v end
      idx[#idx + 1] = i
    end
  end
  return bg, opt, idx
end

local function ffprobe_ms(path_env, file)
  if not file or file == "" or file:sub(1, 1) == "?" then return nil end
  local p = io.popen(path_env .. "ffprobe -v error -show_entries format=duration -of csv=p=0 " .. M.shq(file) .. " 2>/dev/null")
  if not p then return nil end
  local d = tonumber((p:read("*a") or ""):match("[%d%.]+")); p:close()
  return d and math.floor(d * 1000 + 0.5) or nil
end

local function exists(f) local h = f and io.open(f, "r"); if h then h:close(); return true end; return false end

function M.macro(subs)
  local PATH = "PATH=/opt/homebrew/bin:/usr/local/bin:$PATH "
  local info, lines = {}, {}
  for i = 1, #subs do
    local l = subs[i]
    if l.class == "info" then info[l.key] = l.value elseif l.class == "dialogue" then lines[#lines + 1] = l end
  end
  local bg, opt, saved_idx = M.load_saved(subs)
  local pp = aegisub.project_properties and aegisub.project_properties() or {}
  local audio_default = opt.audio or ((pp.audio_file and exists(pp.audio_file)) and pp.audio_file) or ""
  local secs = M.sections(lines)
  if #secs == 0 then aegisub.debug.out("No lyric lines found.\n"); return end
  local styles = M.distinct_styles(secs)

  local dir = aegisub.decode_path("?script/")
  local name = (aegisub.file_name() or "untitled.ass"):gsub("%.[^.]*$", "")
  local w, h = tonumber(info.PlayResX) or 1280, tonumber(info.PlayResY) or 720
  local cfg, y = {}, 0
  cfg[#cfg + 1] = { class = "label", x = 0, y = y, width = 4, label = "Background for each section style (enemy slug like black-antoid-2, or layers like 270,269):" }
  for i, st in ipairs(styles) do
    y = y + 1
    cfg[#cfg + 1] = { class = "label", x = 0, y = y, label = st }
    cfg[#cfg + 1] = { class = "edit", x = 1, y = y, width = 3, name = "bg" .. i, value = M.saved_bg(bg, st) or "" }
  end
  local function row(label, nm, val) y = y + 1
    cfg[#cfg + 1] = { class = "label", x = 0, y = y, label = label }
    cfg[#cfg + 1] = { class = "edit", x = 1, y = y, width = 3, name = nm, value = val } end
  row("Output video", "out", opt.out or (dir .. "/" .. name .. "-bg.mp4"))
  row("Size (WxH)", "size", opt.size or (w .. "x" .. h))
  row("FPS", "fps", opt.fps or "30")
  row("Audio (sets length; optional)", "audio", audio_default)
  row("Extra magic-cake options", "extra", opt.extra or "")
  row("magic-cake command", "cmd", opt.cmd or "magic-cake")
  local btn, r = aegisub.dialog.display(cfg, { "Render", "Save only", "Cancel" }, { ok = "Render", cancel = "Cancel" })
  if not btn or btn == "Cancel" then aegisub.cancel() end

  local specs, missing = {}, {}
  for i, st in ipairs(styles) do
    specs[st] = (r["bg" .. i] or ""):gsub("^%s+", ""):gsub("%s+$", "")
    if specs[st] == "" then missing[#missing + 1] = st end
  end
  -- persist choices (replace old magic-cake comment lines)
  for k = #saved_idx, 1, -1 do subs.delete(saved_idx[k]) end
  local tmpl
  for i = 1, #subs do if subs[i].class == "dialogue" then tmpl = subs[i]; break end end
  local function save(text)
    local l = {}; for k, v in pairs(tmpl) do l[k] = v end
    l.comment, l.effect, l.text, l.start_time, l.end_time, l.layer = true, TAG, text, 0, 0, 0
    subs.append(l)
  end
  for st, sp in pairs(bg) do if specs[st] == nil and specs[M.group(st)] == nil then save("bg:" .. st .. "=" .. sp) end end -- keep unused styles' picks
  for _, st in ipairs(styles) do if specs[st] ~= "" then save("bg:" .. st .. "=" .. specs[st]) end end
  for _, k in ipairs({ "out", "size", "fps", "audio", "extra", "cmd" }) do save("opt:" .. k .. "=" .. (r[k] or "")) end
  aegisub.set_undo_point("Magic Cake settings")
  if btn == "Save only" then return end
  if #missing > 0 then aegisub.debug.out("No background set for: " .. table.concat(missing, ", ") .. "\n"); return end

  local audio = r.audio ~= "" and r.audio or nil
  local end_ms = ffprobe_ms(PATH, audio)
  if not end_ms and pp.video_file then end_ms = ffprobe_ms(PATH, pp.video_file) end
  secs = M.sections(lines, end_ms)
  local chain = aegisub.decode_path("?temp/") .. "/magic-cake-chain.txt"
  local f = assert(io.open(chain, "w")); f:write(M.chain_text(secs, specs)); f:close()

  local cmd = PATH .. r.cmd .. " " .. M.shq(r.out) .. " --chain-file " .. M.shq(chain) ..
    " --size " .. M.shq(r.size) .. " --fps " .. M.shq(r.fps)
  if audio then cmd = cmd .. " --audio " .. M.shq(audio)
  else cmd = cmd .. string.format(" --duration %.3f", secs[#secs].finish / 1000) end
  if r.extra ~= "" then cmd = cmd .. " " .. r.extra end
  aegisub.progress.task("Rendering background (this can take a minute)...")
  aegisub.log(M.chain_text(secs, specs) .. "\n$ " .. cmd .. "\n")
  local p = io.popen(cmd .. " 2>&1; echo __EXIT:$?")
  local outp = p:read("*a"); p:close()
  local code = tonumber(outp:match("__EXIT:(%d+)")) or -1
  outp = outp:gsub("__EXIT:%d+%s*$", ""):gsub("[^\n]*\r", "")
  if code == 0 then
    aegisub.log(outp .. "\nDone. Open it with Video > Open Video:\n" .. r.out .. "\n")
  else
    aegisub.log(outp .. "\nmagic-cake failed (exit " .. code .. "). If it says 'not found', set the full path in 'magic-cake command' (run `which magic-cake` in Terminal).\n")
  end
end

if aegisub then
  aegisub.register_macro(script_name, script_description, M.macro)
end
return M
